class Profile {
  final String nama;
  final String nim;
  final String kelas;
  final String prodi;
  final String bio;
  final String email;
  final String phone;
  final String github;
  final String photo;

  Profile({
    required this.nama,
    required this.nim,
    required this.kelas,
    required this.prodi,
    required this.bio,
    required this.email,
    required this.phone,
    required this.github,
    required this.photo,
  });
}
